import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import DEFAULT from '../worker/default-config.js';

const source=await readFile('public/game.js','utf8');
const context=vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function ceremonyStart('),source.indexOf('const ceremonyCountdown=')),context);
const {ceremonyStart,countdownText}=context;
const start=Date.parse('2026-10-04T08:00:00+07:00');
assert.equal(ceremonyStart(DEFAULT),start);
assert.equal(countdownText(start,Date.parse('2026-10-01T10:30:00+07:00')),'2 hari · 21:30:00');
assert.equal(countdownText(start,start-1000),'0 hari · 00:00:01');
assert.equal(countdownText(start,start),'Akad telah dimulai');
assert.equal(countdownText(start,start+1000),'Akad telah dimulai');
assert.equal(countdownText(null,Date.now()),'Jadwal akad segera hadir');
const custom=structuredClone(DEFAULT),event=custom.places.find(p=>p.id==='ceremony').events[0];
event.date='Senin, 5 Oktober 2026';event.time='09:30–12:00 WIB';
assert.equal(ceremonyStart(custom),Date.parse('2026-10-05T09:30:00+07:00'));
event.time='09.30–12.00 WITA';assert.equal(ceremonyStart(custom),Date.parse('2026-10-05T09:30:00+08:00'));
event.time='09.30 WIT';assert.equal(ceremonyStart(custom),Date.parse('2026-10-05T09:30:00+09:00'));
event.date='29 Februari 2028';assert.ok(ceremonyStart(custom));
event.date='29 Februari 2027';assert.equal(ceremonyStart(custom),null);
event.date='31 April 2026';assert.equal(ceremonyStart(custom),null);
event.date='5 Oktober 2026';event.time='24.00';assert.equal(ceremonyStart(custom),null);
event.time='08.60';assert.equal(ceremonyStart(custom),null);
event.time='Akan diumumkan';assert.equal(ceremonyStart(custom),null);
assert.doesNotMatch(source,/networkStatus|pemain online/);
console.log('PASS: CMS schedule, timezone independence, live countdown, deadline and invalid-date handling');
